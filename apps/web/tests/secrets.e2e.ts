import { randomUUID } from "node:crypto"
import { expect, secrets } from "e2e"
import { test } from "./fixtures"

test("create, edit, reveal and revoke an encrypted env group", async ({ app, browser, screen }) => {
  const slug = `browser-${randomUUID()}`
  const original = "fake-browser-env-value"
  const edited = "fake-edited-env-value"
  await app.open("/secrets/new")
  await screen.getByLabel("Group name").fill(slug)
  await screen.getByLabel("Project", { exact: true }).fill("Browser project")
  await screen.getByLabel("Environment").selectOption({ value: "staging" })
  await screen.getByText("Paste a .env file", { exact: true }).tap()
  await screen.getByLabel("File contents").fill(`API_KEY=${original}\nSECOND_KEY=other-fake-value`)
  await screen.getByRole("button", "Import variables", { exact: true }).tap()
  await screen.getByRole("button", "Save secrets", { exact: true }).tap()
  await expect(browser).toHaveURL(/\/secrets\/[0-9a-f-]+$/)
  const ownerUrl = await browser.url()
  await expect(screen.getByRole("heading", slug)).toBeVisible()
  await expect(browser.locator("body")).not.toContainText(original)
  const initial = await browser.evaluate(async (marker: string) => {
    const response = await fetch(window.location.href, { cache: "no-store" })
    return {
      containsValue: (await response.text()).includes(marker),
      cacheControl: response.headers.get("cache-control"),
      referrer: response.headers.get("referrer-policy"),
    }
  }, original)
  expect(initial.containsValue).toBe(false)
  expect(initial.cacheControl).toContain("no-store")
  expect(initial.referrer).toBe("no-referrer")
  await screen.getByRole("button", "Reveal", { exact: true }).nth(0).tap()
  await expect(screen.getByText(original, { exact: true })).toBeVisible()
  await screen.getByRole("button", "Hide all", { exact: true }).tap()
  await expect(browser.locator("body")).not.toContainText(original)
  await screen.getByRole("button", "Edit group", { exact: true }).tap()
  await screen.getByRole("button", "Cancel", { exact: true }).tap()
  await expect(screen.getByRole("button", "Edit group", { exact: true })).toBeVisible()
  await screen.getByRole("button", "Edit group", { exact: true }).tap()
  await screen.getByLabel("New value", { exact: true }).nth(0).fill(edited)
  await screen.getByRole("button", "Save secrets", { exact: true }).tap()
  await expect(screen.getByRole("button", "Edit group", { exact: true })).toBeVisible()
  await expect(browser.locator("body")).not.toContainText(edited)
  await browser.reload()
  await expect(browser.locator("body")).not.toContainText(edited)
  await screen.getByLabel("Link password", { exact: true }).fill(secrets.get("pastePassword"))
  await screen.getByRole("button", "Create protected link", { exact: true }).tap()
  await expect(screen.getByLabel("Protected link", { exact: true })).toBeVisible()
  const link = await screen.getByLabel("Protected link", { exact: true }).inputValue()
  const cookies = await browser.cookies()
  await app.clearState()
  await browser.goto(link)
  await expect(screen.getByRole("heading", "Protected secrets", { exact: true })).toBeVisible()
  await expect(browser.locator("body")).not.toContainText("API_KEY")
  await expect(browser.locator("body")).not.toContainText(edited)
  await screen.getByLabel("Link password", { exact: true }).fill(secrets.get("wrongPassword"))
  await screen.getByRole("button", "Reveal secrets", { exact: true }).tap()
  await expect(screen.getByRole("alert").filter({ hasText: "password incorrect" })).toBeVisible()
  await screen.getByLabel("Link password", { exact: true }).fill(secrets.get("pastePassword"))
  await screen.getByRole("button", "Reveal secrets", { exact: true }).tap()
  await expect(screen.getByText(edited, { exact: true })).toBeVisible()
  await screen.getByRole("button", "Hide all", { exact: true }).tap()
  await expect(browser.locator("body")).not.toContainText(edited)
  await browser.setCookies(cookies)
  await browser.goto(ownerUrl)
  await screen.getByRole("button", "Revoke", { exact: true }).tap()
  await expect(screen.getByText("No active links. This group is private.")).toBeVisible()
  await app.clearState()
  await browser.goto(link)
  await screen.getByLabel("Link password", { exact: true }).fill(secrets.get("pastePassword"))
  await screen.getByRole("button", "Reveal secrets", { exact: true }).tap()
  await expect(screen.getByRole("alert").filter({ hasText: "Link unavailable" })).toBeVisible()
  await expect(browser.locator("body")).not.toContainText(edited)
  await browser.setCookies(cookies)
  await browser.setViewport({ width: 390, height: 844 })
  await app.open("/settings")
  await expect(screen.getByRole("link", "Starred", { exact: true, visible: true })).toBeVisible()
  await screen.getByRole("link", "Secrets", { exact: true, visible: true }).tap()
  await expect(browser).toHaveURL("/secrets")
  await expect(screen.getByRole("heading", "Browser project", { exact: true })).toBeVisible()
})
